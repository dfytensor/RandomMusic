def cohen_d(a, b):
    a, b = np.array(a, float), np.array(b, float)
    s = np.sqrt(((len(a)-1)*a.var() + (len(b)-1)*b.var()) / (len(a)+len(b)-2))
    return float((a.mean() - b.mean()) / (s + 1e-9))


